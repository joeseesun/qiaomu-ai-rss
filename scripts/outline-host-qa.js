// Run as an async function body in the isolated qrs-outline-qa Obsidian vault.
if (app.vault.adapter.basePath !== '/tmp/qrs-outline-qa') throw Error('QA vault only');
const p = app.plugins.plugins['qiaomu-ai-rss'];
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
const until = async test => { for (let n=0;n<80;n++) { if(test()) return; await wait(25); } throw Error('Condition timed out'); };
const checks = [], check = (name, pass) => { checks.push({name,pass:!!pass}); if(!pass) throw Error(JSON.stringify(checks)); };
const win = require('electron').remote.getCurrentWindow();
win.setSize(1440, 1000);win.show();
app.workspace.leftSplit.collapse();
await p.openReader();
const v = app.workspace.getLeavesOfType('qiaomu-ai-rss-reader')[0].view;
const fixture = p.state.subscriptions[0].entries[0];
await v.openArticle(fixture);
const reader = () => v.outlineContext().scroller;
const panel = () => app.workspace.getLeavesOfType('qiaomu-ai-rss-outline')[0]?.view;
const rows = () => [...panel().contentEl.querySelectorAll('.qrs-outline-row')];
const active = () => rows().findIndex(row=>row.hasAttribute('aria-current'));
const click = el => { el.dispatchEvent(new PointerEvent('pointerdown',{bubbles:true}));el.click(); };
if(!panel()) click(v.contentEl.querySelector('[data-qrs-outline]'));
await until(()=>panel()?.contentEl.querySelectorAll('.qrs-outline-row').length === 12);
check('renders twelve real headings', rows().length===12);
const actions = [...v.contentEl.querySelector('.qrs-actions').children];
check('toolbar order is outline, appearance, play', actions[0].hasAttribute('data-qrs-outline') && actions[1].hasAttribute('data-qrs-appearance') && actions[2].classList.contains('qrs-speech-slot'));
rows()[3].click();await until(()=>active()===3);
let heading = v.outlineContext().prose.querySelectorAll('h2,h3')[3];
check('duplicate heading jumps below sticky toolbar',Math.abs(heading.getBoundingClientRect().top-reader().querySelector('.qrs-reader-head').getBoundingClientRect().bottom-16)<2);
reader().scrollTo({top:0});await until(()=>active()===0);
check('scroll updates active heading',active()===0);
reader().scrollTo({top:reader().scrollHeight});await until(()=>active()===11);
check('last heading active at end',active()===11);
const prose = v.outlineContext().prose, top = reader().scrollTop;
click(v.contentEl.querySelector('[data-qrs-appearance]'));
check('appearance opens without rebuilding article or resetting scroll', !!v.contentEl.querySelector('.qrs-reading-settings') && v.outlineContext().prose===prose && reader().scrollTop===top);
check('appearance button reports expanded state', v.contentEl.querySelector('[data-qrs-appearance]').getAttribute('aria-expanded')==='true');
click(v.contentEl.querySelector('[data-qrs-appearance]'));
check('appearance closes on second click', !v.contentEl.querySelector('.qrs-reading-settings'));
const sample = {entry:{id:'outline-versions',sourceId:'qa',title:'版本切换验收',content:'<h2>Original heading</h2><p>Original body</p>'},rewrite:{body:'## 改写标题\n\n正文\n\n### 改写小节\n\n正文'},translation:{content:[{target:'翻译标题',sourceHtml:'<h2>Original heading</h2>'},{target:'翻译正文'}]},fetchedAt:1};
v.showSavedArticle(sample,'original');await until(()=>rows().length===1 && rows()[0].textContent==='Original heading');
const select = mode => { const s=v.contentEl.querySelector('.qrs-mode-select');s.value=mode;s.dispatchEvent(new Event('change')); };
select('rewrite');await until(()=>rows().length===2 && rows()[0].textContent==='改写标题');
check('rewrite version updates outline',rows()[1].textContent==='改写小节');
select('translation');await until(()=>rows().length===1 && rows()[0].textContent==='翻译标题');
check('translation preserves heading level',v.outlineContext().prose.querySelector('h2').textContent==='翻译标题');
v.showSavedArticle({...sample,entry:{...sample.entry,id:'outline-empty',title:'没有标题的文章',content:'<p><strong>加粗文字不是小标题</strong></p>'}},'original');
check('no fake headings from bold text',rows().length===0 && panel().contentEl.querySelector('.qrs-outline-empty').textContent.includes('没有小标题'));
v.showSavedArticle({...sample,entry:{id:'outline-markdown',sourceId:'qa',origin:'vault',title:'本地笔记',markdownPath:'目录验收.md',markdown:'# 本地章节\n\n正文\n\n## 子章节\n\n正文'}},'original');
await until(()=>rows().length===2 && rows()[1].textContent==='子章节');
check('asynchronous native Markdown refreshes outline',rows()[0].textContent==='本地章节');
// Switch away immediately, then allow the old Markdown renderer to finish.
v.showSavedArticle({...sample,entry:{id:'outline-late',sourceId:'qa',origin:'vault',title:'迟到笔记',markdownPath:'目录验收.md',markdown:'## 不应回来的旧目录'}},'original');
v.showSavedArticle(sample,'original');await wait(250);
check('late render cannot restore previous outline',rows().length===1 && rows()[0].textContent==='Original heading');
await v.openArticle(fixture);await until(()=>rows().length===12);
reader().scrollTo({top:0});await wait(100);
const fs=require('fs'),out='/tmp/qrs-outline-artifacts/';fs.mkdirSync(out,{recursive:true});
const capture = async name => {await wait(150);fs.writeFileSync(out+name,(await win.webContents.capturePage()).toPNG());};
const colors = {};
for (const [theme,readingTheme] of [['light','light'],['dark','dark'],['paper','paper']]) {
 document.body.classList.toggle('theme-dark',theme==='dark');document.body.classList.toggle('theme-light',theme!=='dark');p.state.settings.readingTheme=readingTheme;v.refreshReadingTheme();
 await wait(100);
 const outline=v.contentEl.querySelector('[data-qrs-outline]'),play=v.contentEl.querySelector('.qrs-speech-slot > button');
 colors[theme]={outline:getComputedStyle(outline).color,play:getComputedStyle(play).color,bg:getComputedStyle(reader()).backgroundColor};
 check(theme+' outline and play share quiet color',colors[theme].outline===colors[theme].play);
 await capture('outline-'+theme+'.png');
}
p.state.settings.readingTheme='auto';document.body.classList.remove('theme-dark');document.body.classList.add('theme-light');v.refreshReadingTheme();
// Resize only the isolated QA window. On phones the native right drawer is used.
win.setSize(720,920);await wait(200);
const toolbar=v.contentEl.querySelector('.qrs-reader-toolbar');
check('narrow toolbar has no horizontal overflow',toolbar.scrollWidth<=toolbar.clientWidth+1);
const controls=[...v.contentEl.querySelectorAll('[data-qrs-outline],[data-qrs-appearance],.qrs-speech-slot > button,[data-qrs-article-more]')].map(el=>({x:el.getBoundingClientRect().left,width:el.getBoundingClientRect().width}));
check('narrow controls retain touch targets',controls.every(c=>c.width>=40));
await capture('outline-narrow.png');
win.setSize(1440,1000);await wait(150);
const before=rows()[0];v.renderReader(true);
check('toolbar-only updates preserve directory focus targets',rows()[0]===before);
click(v.contentEl.querySelector('[data-qrs-outline]'));await until(()=>!panel());
check('toolbar closes outline',v.contentEl.querySelector('[data-qrs-outline]').getAttribute('aria-pressed')==='false');
click(v.contentEl.querySelector('[data-qrs-outline]'));await until(()=>rows().length===12);
check('reopen has exactly one panel',app.workspace.getLeavesOfType('qiaomu-ai-rss-outline').length===1);
const result={checks,colors,controls};fs.writeFileSync(out+'outline-host-result.json',JSON.stringify(result,null,2));
return result;
